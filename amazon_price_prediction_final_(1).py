def get_embeddings_batch(texts, images, batch_size=32):
    """
    Correct way to get CLIP embeddings.
    Pass BOTH text and image together to CLIP.
    Returns text_embeds and image_embeds directly as tensors.
    No dimension mismatch! Both are 512.
    """
    all_text_embs  = []
    all_image_embs = []

    for i in range(0, len(texts), batch_size):
        batch_texts  = texts[i:i+batch_size]
        batch_images = images[i:i+batch_size]

        with torch.no_grad():
            inputs = clip_processor(
                text=batch_texts,
                images=batch_images,
                return_tensors='pt',
                padding=True,
                truncation=True,
                max_length=77
            )
            inputs = {k: v.to(device) for k, v in inputs.items()}

            # Pass both together - returns text_embeds and image_embeds directly!
            outputs = clip_model(**inputs)

            # Get embeddings directly - both are 512 dim, no mismatch!
            t_emb = outputs.text_embeds
            i_emb = outputs.image_embeds

            # L2 normalize
            t_emb = t_emb / (t_emb.norm(dim=-1, keepdim=True) + 1e-12)
            i_emb = i_emb / (i_emb.norm(dim=-1, keepdim=True) + 1e-12)

            all_text_embs.append(t_emb.cpu().numpy())
            all_image_embs.append(i_emb.cpu().numpy())

    return np.vstack(all_text_embs), np.vstack(all_image_embs)


def gated_fusion(text_embs, image_embs):
    """
    Gated Fusion for all products at once.
    Gate = sigmoid(dot product of text and image)
    Decides how much weight to give text vs image per product.
    """
    fused = []
    for t, i in zip(text_embs, image_embs):
        gate  = 1 / (1 + np.exp(-np.dot(t, i)))
        fused.append(gate * t + (1 - gate) * i)
    return np.array(fused)


