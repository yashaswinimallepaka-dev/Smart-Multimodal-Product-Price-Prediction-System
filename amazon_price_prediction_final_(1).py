def clean_text(text):
    if not isinstance(text, str):
        return ''
    text = html.unescape(text)
    text = re.sub(r'(Bullet Point \d+:|Item Name:|Value:|Unit:|Description:)', '', text)
    text = re.sub(r'\s+', ' ', text).strip()
    return text[:500]

